def main() -> None:
    """Standalone test: create a PPTX with a summary slide."""
    prs = Presentation()
    prs.slide_width = _SLIDE_W
    prs.slide_height = _SLIDE_H

    summary = _demo_summary()

    ok = append_summary_slide(prs, summary)
    if not ok:
        print("ERROR: Failed to build summary slide", file=sys.stderr)
        sys.exit(1)

    out_path = Path(__file__).parent / "test_output_with_summary.pptx"
    prs.save(str(out_path))
    print(f"Created: {out_path}")
    print(f"  Slides in file: {len(prs.slides)}")
    print(f"  Summary appended: {ok}")


if __name__ == "__main__":
    main()
